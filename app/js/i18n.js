const DICTS = { en: EN };

let current;
/** Langue de l'interface : réglage de l'utilisateur, sinon celle de l'appareil. */
export function lang() {
  if (current) return current;
  let pref = 'auto';
  try { pref = JSON.parse(localStorage.getItem('scrollarr.settings'))?.lang || 'auto'; } catch { /* réglages illisibles */ }
  if (pref === 'auto') pref = (navigator.language || 'fr').slice(0, 2).toLowerCase();
  current = pref === 'fr' || DICTS[pref] ? pref : 'en';
  return current;
}

export function t(key, params) {
  const s = DICTS[lang()]?.[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m)) : s;
}
